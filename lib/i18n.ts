// Shop languages. English is the default; text is written in English in the code and
// looked up here for Swedish. Anything missing from the Swedish list falls back to English.
export const LANGS = ['en', 'sv'] as const;
export type Lang = (typeof LANGS)[number];
export const DEFAULT_LANG: Lang = 'en';
export const LANG_COOKIE = 'lang';
export const LANG_LABEL: Record<Lang, string> = { en: 'English', sv: 'Svenska' };

export const isLang = (v: unknown): v is Lang => typeof v === 'string' && (LANGS as readonly string[]).includes(v);

type Vars = Record<string, string | number>;
export type T = (text: string, vars?: Vars) => string;

const fill = (s: string, vars?: Vars) => (vars ? s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m)) : s);

/** Returns the translate function for a language: t('Your basket') → 'Din varukorg'. */
export function translator(lang: Lang): T {
  const table = lang === 'sv' ? sv : null;
  return (text, vars) => fill((table && table[text]) || text, vars);
}

