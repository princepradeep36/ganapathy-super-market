/** Server error messages that carry numbers or names; translated by pattern. */
const ERROR_PATTERNS: [RegExp, string][] = [
  [/^Only (\d+) × (.+) left in stock$/, 'Endast $1 × $2 kvar i lager'],
  [/^We only deliver within (.+)\. Please choose store pickup\.$/, 'Vi levererar endast inom $1. Välj upphämtning i butik.'],
  [/^Minimum order for delivery is (.+)$/, 'Minsta order för hemleverans är $1'],
  [/^Add (.+) kr more to use this code$/, 'Handla för $1 kr till för att använda koden'],
];
export function translateError(lang: Lang, msg: string) {
  if (lang !== 'sv' || !msg) return msg;
  if (sv[msg]) return sv[msg];
  for (const [re, out] of ERROR_PATTERNS) if (re.test(msg)) return msg.replace(re, out);
  return msg;
}

